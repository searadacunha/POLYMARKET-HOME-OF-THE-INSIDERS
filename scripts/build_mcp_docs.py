#!/usr/bin/env python3
"""Write the tool tables of docs/mcp.md and phi_forensics/README.md from phi_forensics.mcp.server.tools().

    python3 scripts/build_mcp_docs.py            # rewrite the generated blocks
    python3 scripts/build_mcp_docs.py --check    # exit 1 when a committed block differs from the tool list

Only the text between the BEGIN and END markers is generated; the rest of each file is written by hand.
"""
import argparse
import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from phi_forensics.mcp import server  # noqa: E402

BLOCK = re.compile(r"(<!-- BEGIN tools .*?-->\n).*?(<!-- END tools -->)", re.S)
WIDTH = 118
MARK = "<!-- BEGIN tools (generated by scripts/build_mcp_docs.py, do not edit) -->\n"


def _argument(name, schema, required):
    kind = schema.get("type")
    if "enum" in schema:
        kind = "one of " + ", ".join(schema["enum"])
    elif kind == "array":
        kind = f"{schema.get('minItems', 0)} to {schema.get('maxItems')} {schema['items'].get('type')}s"
    elif "minimum" in schema:
        kind += f" {schema['minimum']} to {schema['maximum']}" if "maximum" in schema else f" from {schema['minimum']}"
    elif "pattern" in schema:
        kind += f" `{schema['pattern']}`"
    note = f", {schema['description'].rstrip('.')}" if schema.get("description") else ""
    return f"`{name}`{' (required)' if required else ''}: {kind}{note}"


def _wrap(text, indent=""):
    return textwrap.fill(text, WIDTH, initial_indent=indent, subsequent_indent=" " * len(indent), break_on_hyphens=False)


def table(tools):
    """A summary table, then one section per tool: Markdown tables cannot wrap, so the long text sits below them."""
    rows = ["| Tool | Title | Arguments (* required) |", "| --- | --- | --- |"]
    for tool in tools:
        args = ", ".join(f"`{n}`" + ("*" if n in tool.schema["required"] else "") for n in tool.schema["properties"]) or "none"
        rows.append(f"| [`{tool.name}`](#{tool.name}) | {tool.title} | {args} |")
    for tool in tools:
        rows += ["", f"### {tool.name}", "", _wrap(tool.description), ""]
        rows += [_wrap(_argument(n, s, n in tool.schema["required"]), "- ") for n, s in tool.schema["properties"].items()] or ["No argument."]
    return "\n".join(rows) + "\n"


def names(tools):
    live = ", ".join(f"`{t.name}`" for t in tools if t.open_world)
    offline = ", ".join(f"`{t.name}`" for t in tools if not t.open_world)
    return (_wrap(f"Live ({sum(t.open_world for t in tools)}, public APIs and Polygon nodes): {live}.", "- ") + "\n"
            + _wrap(f"Offline ({sum(not t.open_world for t in tools)}, the archives of a checkout and the server status): {offline}.", "- ")
            + "\n")


TARGETS = {"docs/mcp.md": table, "phi_forensics/README.md": names}


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when a generated block is stale, write nothing")
    check = parser.parse_args().check
    tools, stale = server.tools(), []
    for path, render in TARGETS.items():
        text = (ROOT / path).read_text(encoding="utf-8")
        if not BLOCK.search(text):
            raise SystemExit(f"{path}: no BEGIN tools / END tools markers")
        new = BLOCK.sub(lambda m: MARK + render(tools) + m.group(2), text)
        if new != text:
            stale.append(path)
            if not check:
                (ROOT / path).write_text(new, encoding="utf-8")
    if check and stale:
        print(f"stale: {', '.join(stale)}; run python3 scripts/build_mcp_docs.py", file=sys.stderr)
        return 1
    print(("written: " + ", ".join(stale)) if stale and not check else "up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
