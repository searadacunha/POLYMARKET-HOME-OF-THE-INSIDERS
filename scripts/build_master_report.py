#!/usr/bin/env python3
"""Generate MASTER_REPORT.md, INVENTORY.md and datasets/manifests/local_only.json.

Only reads investigations/*/{STATUS,FINDINGS}.md and data_manifest.json. Never edit the outputs
by hand: fix the investigation file and run this again. --check fails if the outputs are stale.
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import phi_lib as lib  # noqa: E402

STATE_LABEL = {"DONE": "Done", "IN_PROGRESS": "In progress", "PAUSED": "Paused", "ABANDONED": "Abandoned"}
LEVEL_TITLE = {
    "CONFIRMED": "Demonstrated (CONFIRMED)",
    "SUPPORTED": "Supported, proof incomplete (SUPPORTED)",
    "HYPOTHESIS": "Not demonstrated, interpretation only (HYPOTHESIS)",
    "REFUTED": "Refuted, negative results (REFUTED)",
    "UNRESOLVED": "Unresolved, not enough data (UNRESOLVED)",
}
HEADER = "<!-- Generated by scripts/build_master_report.py. Do not edit by hand. -->\n"


def load():
    investigations = []
    for inv_dir in lib.investigation_dirs():
        status_path, findings_path = inv_dir / "STATUS.md", inv_dir / "FINDINGS.md"
        if not status_path.exists() or not findings_path.exists():
            continue
        fields, body = lib.parse_status(status_path.read_text())
        findings, sections = lib.parse_findings(findings_path.read_text())
        investigations.append({"id": inv_dir.name, "fields": fields or {}, "body": body.strip(), "findings": findings,
                               "sections": sections, "manifest": lib.load_manifest(inv_dir) or {"files": [], "counts": {}}})
    return investigations


def status_section(body, title):
    match = re.search(rf"^## {re.escape(title)}\n(.*?)(?=^## |\Z)", body, re.S | re.M)
    return " ".join(match.group(1).split()) if match else ""


def mb(n):
    return f"{n / 1e6:,.1f} MB"


def local_only_rows(manifest):
    rows = [e for e in manifest["files"] if e.get("status") == "local_only"]
    return sum(e.get("files", 1) for e in rows), sum(e.get("size", 0) for e in rows), rows


def report(investigations):
    out = [HEADER, "# Master report\n"]
    total_findings = sum(len(i["findings"]) for i in investigations)
    out.append(f"{len(investigations)} investigations, {total_findings} classified findings. Each line points to the "
               "`FINDINGS.md` of its investigation, which cites its sources. A finding claims no more than its level.\n")
    out.append("Three readings this report never allows: a wallet labeled ChangeNOW does not identify its owner; a deposit "
               "into ChangeNOW followed by a later payout does not prove a transfer between the same people; suspicious "
               "bets do not by themselves prove insider trading.\n")
    out.append("## All investigations\n")
    out.append("| Investigation | State | Version | Updated | Findings |\n|---|---|---|---|---|")
    for inv in investigations:
        f = inv["fields"]
        counts = " ".join(f"{level[:4]}:{n}" for level in lib.LEVELS
                          if (n := sum(1 for x in inv["findings"] if x["level"] == level)))
        out.append(f"| [{f.get('title', inv['id'])}](investigations/{inv['id']}/README.md) | "
                   f"{STATE_LABEL.get(f.get('state'), f.get('state'))} | {f.get('version', '')} | "
                   f"{f.get('updated_utc', '')[:10]} | {counts or 'none'} |")
    out.append("")
    for state in lib.STATES:
        names = [i["id"] for i in investigations if i["fields"].get("state") == state]
        if names:
            out.append(f"- **{STATE_LABEL[state]}**: " + ", ".join(f"`{n}`" for n in names))
    out.append("")
    for level in lib.LEVELS:
        out.append(f"## {LEVEL_TITLE[level]}\n")
        rows = [(i, x) for i in investigations for x in i["findings"] if x["level"] == level]
        if not rows:
            out.append("Nothing at this level.\n")
        for inv, finding in rows:
            note = " *(investigation in progress: provisional)*" if inv["fields"].get("state") == "IN_PROGRESS" else ""
            out.append(f"- **{inv['id']}:{finding['id']}** {finding['claim']}{note}")
            out.append(f"  - Limits: {finding.get('Limits', '')}")
        out.append("")
    out.append("## Verified links between investigations\n")
    links = [(i["id"], x["id"], x["Links"]) for i in investigations for x in i["findings"]
             if x.get("Links", "").strip().lower() not in ("", "none")]
    if not links:
        out.append("None.\n")
    for inv_id, finding_id, text in links:
        out.append(f"- `{inv_id}:{finding_id}`: {text}")
    out.append("")
    for title, heading in (("Contradictions", "Contradictory findings"), ("Missing to conclude", "What is missing to conclude"),
                           ("Prospective monitoring", "Prospective monitoring")):
        out.append(f"## {heading}\n")
        rows = [(i["id"], line) for i in investigations for line in i["sections"].get(title, [])]
        if not rows:
            out.append("Nothing reported.\n")
        for inv_id, line in rows:
            out.append(f"- `{inv_id}`: {line}")
        out.append("")
    out.append("## Data not archived here\n")
    out.append("These files are NOT in this repository. They exist only on the original machine, with their hash in the "
               "manifest. Details: [datasets/manifests/local_only.json](datasets/manifests/local_only.json).\n")
    out.append("| Investigation | Files | Size | Refused by the scan |\n|---|---:|---:|---:|")
    for inv in investigations:
        count, size, _ = local_only_rows(inv["manifest"])
        refused = sum(1 for e in inv["manifest"]["files"] if e.get("status") == "refused")
        out.append(f"| `{inv['id']}` | {count} | {mb(size)} | {refused} |")
    out.append("")
    return "\n".join(out)


def inventory(investigations, extra):
    out = [HEADER, "# Inventory\n"]
    out.append("Generated from each `STATUS.md` and manifest. An id is a folder `investigations/<id>/` and a branch `investigation/<id>`.\n")
    for inv in investigations:
        f, m = inv["fields"], inv["manifest"]
        count, size, _ = local_only_rows(m)
        c = m.get("counts", {})
        out.append(f"## {inv['id']}\n")
        out.append(f"- **Title**: {f.get('title', '')}")
        out.append(f"- **Original location**: `{f.get('origin', '')}`")
        out.append(f"- **Actual state**: {STATE_LABEL.get(f.get('state'), f.get('state'))}")
        out.append(f"- **Last commit and version**: {f.get('version', '')}")
        out.append(f"- **Snapshot**: {m.get('snapshot_utc', 'none')}")
        for label, title in (("Objective", "Objective"), ("Conclusions", "Conclusions"), ("Limits", "Limits"), ("Links", "Links with other investigations")):
            text = status_section(inv["body"], label)
            if text:
                out.append(f"- **{title}**: {text}")
        out.append(f"- **Data**: {c.get('imported', 0)} files published ({mb(m.get('imported_bytes', 0))}), "
                   f"{c.get('duplicate', 0)} duplicates pointing to another investigation, "
                   f"{count} files NOT archived ({mb(size)}), {c.get('refused', 0)} refused by the scan.")
        out.append("")
    if extra.exists():
        out.append(extra.read_text())
    return "\n".join(out)


def local_only_index(investigations):
    rows = []
    for inv in investigations:
        for entry in local_only_rows(inv["manifest"])[2]:
            rows.append({"investigation": inv["id"], "origin": inv["manifest"].get("origin"), **entry})
    return json.dumps({"note": "Files NOT archived in this repository.", "entries": rows}, indent=1, ensure_ascii=False) + "\n"


def main():
    investigations = load()
    outputs = {
        lib.REPO / "MASTER_REPORT.md": report(investigations),
        lib.REPO / "INVENTORY.md": inventory(investigations, lib.REPO / "datasets" / "OUTSIDE_INVESTIGATIONS.md"),
        lib.REPO / "datasets" / "manifests" / "local_only.json": local_only_index(investigations),
    }
    if "--check" in sys.argv:
        stale = [str(p.relative_to(lib.REPO)) for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        print("stale: " + ", ".join(stale) if stale else "reports up to date")
        return 1 if stale else 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(f"{len(investigations)} investigations, {sum(len(i['findings']) for i in investigations)} findings")
    return 0


if __name__ == "__main__":
    sys.exit(main())
