#!/usr/bin/env python3
"""Synthesis of the positive and negative controls, freeze gate applied mechanically (plan section
'Positive and negative controls'). Reads controles/controls_*.json, writes controles/summary.json and
controles/positive_controls.md. Synthetic data only.

Gate (all required to freeze):
  G1 STRONG: T1 rejects at the first Holm threshold (p <= 0.05/7) in every seed;
  G2 STRONG: detection rate >= 0.90 of injected markets in every seed;
  G3 NULL: T1 p <= 0.05 in at most 2 of 10 seeds (expected 0.5; P(>= 3) = 0.012 under a valid test);
  G4 PERMUTED (labels permuted within category-month strata): T1 p > 0.05.
Reported, not gating: MEDIUM / WEAK / OLD power, FUNDLINK T5 power, T4 alongside T1, and the NULL mean T1
statistic (overfitting bias of M3 under no information, used by the verdict).

usage: ctl_45_summary.py controles
"""
import glob
import json
import os
import sys

THR = 0.05 / 7


def main():
    d = sys.argv[1]
    runs = {}
    for f in sorted(glob.glob(os.path.join(d, "controls_*.json"))):
        r = json.load(open(f))
        sc = r["tag"].split("_")[0]
        runs.setdefault(sc, []).append(r)
    rows, out = [], {"scenarios": {}}
    for sc, rs in sorted(runs.items()):
        t1p = [r["tests"]["T1"].get("p") for r in rs]
        t1s = [r["tests"]["T1"].get("stat") for r in rs]
        t4p = [r["tests"].get("T4", {}).get("p") for r in rs]
        t5p = [r["tests"].get("T5", {}).get("p") for r in rs]
        det = [(r.get("detection") or {}).get("rate") for r in rs]
        s = {"seeds": len(rs), "T1_p": t1p, "T1_stat": t1s, "T4_p": t4p, "T5_p": t5p, "detection_rate": det,
             "T1_reject_holm1": sum(1 for p in t1p if p is not None and p <= THR),
             "T1_p_le_0.05": sum(1 for p in t1p if p is not None and p <= 0.05),
             "T5_reject_holm1": sum(1 for p in t5p if p is not None and p <= THR),
             "T1_stat_mean": (sum(x for x in t1s if x is not None) / max(1, sum(1 for x in t1s if x is not None)))}
        out["scenarios"][sc] = s
    S = out["scenarios"]
    g = {}
    st = S.get("STRONG", {})
    g["G1_strong_T1_all_seeds"] = bool(st) and st["T1_reject_holm1"] == st["seeds"] and st["seeds"] >= 5
    g["G2_strong_detection_ge_0.90"] = bool(st) and all(x is not None and x >= 0.90 for x in st["detection_rate"])
    nu = S.get("NULL", {})
    g["G3_null_T1_p_le_0.05_at_most_2_of_10"] = bool(nu) and nu["seeds"] >= 10 and nu["T1_p_le_0.05"] <= 2
    pe = S.get("PERMUTED", {})
    g["G4_permuted_T1_p_gt_0.05"] = bool(pe) and all(p is not None and p > 0.05 for p in pe["T1_p"])
    out["gate"] = g
    out["passed"] = all(g.values())
    out["null_T1_mean"] = nu.get("T1_stat_mean") if nu else None
    json.dump(out, open(os.path.join(d, "summary.json"), "w"), indent=1, sort_keys=True)
    lines = ["# Positive and negative controls (synthetic, TRAIN only)", "",
             "Generated by `code/ctl_45_summary.py` from `controles/controls_*.json`. Mock split of TRAIN events",
             "(70 / 30 by event hash); whole pipeline (detector, panel, models, T1 / T4 / T5, p = max of the event-",
             "cluster and wallet-cluster bootstraps, as in the real tests). Threshold for 'reject': p <= 0.05/7 (first Holm step).", "",
             "| Scenario | Seeds | T1 rejects (p <= 0.0071) | T1 p <= 0.05 | mean T1 ΔLL | detection rate | T5 rejects |",
             "|---|---:|---:|---:|---:|---|---:|"]
    for sc, s in sorted(S.items()):
        det = ", ".join("—" if x is None else f"{x:.2f}" for x in s["detection_rate"])
        lines.append(f"| {sc} | {s['seeds']} | {s['T1_reject_holm1']} | {s['T1_p_le_0.05']} | "
                     f"{s['T1_stat_mean']:+.4f} | {det} | {s['T5_reject_holm1']} |")
    lines += ["", "## Gate", ""] + [f"- {k}: {'PASS' if v else 'FAIL'}" for k, v in g.items()]
    lines += ["", f"**Gate {'PASSED' if out['passed'] else 'FAILED'}.** NULL mean T1 ΔLL (overfitting bias used by",
              f"the verdict): {out['null_T1_mean']}.", "",
              "Per-seed p values and statistics: `controles/summary.json`."]
    open(os.path.join(d, "positive_controls.md"), "w").write("\n".join(lines) + "\n")
    print(json.dumps({"gate": g, "passed": out["passed"]}))


if __name__ == "__main__":
    main()
